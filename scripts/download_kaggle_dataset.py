#!/usr/bin/env python3
"""
download_kaggle_dataset.py
--------------------------
Download a Kaggle weapon detection dataset and organise it into YOLO format.

Default dataset (recommended, no configuration needed):
  techzizou/labeled-weapon-detection-yolo-txt
  ~3,700 images, pre-split train/val/test, classes: Handgun, Knife

Usage (recommended – uses default dataset):
    python scripts/download_kaggle_dataset.py

Usage (custom dataset):
    python scripts/download_kaggle_dataset.py --dataset owner/dataset-name

Prerequisites:
    1. pip install kaggle
    2. Download kaggle.json from https://www.kaggle.com/settings → API
    3. Place at: C:/Users/<you>/.kaggle/kaggle.json   (Windows)
                 ~/.kaggle/kaggle.json               (Linux/Mac)
    4. kaggle.json must contain: {"username":"...","key":"..."}

Output structure:
    dataset/
    ├── images/
    │   ├── train/  (*.jpg)
    │   ├── val/
    │   └── test/
    ├── labels/
    │   ├── train/  (*.txt  YOLO format)
    │   ├── val/
    │   └── test/
    └── data.yaml
"""
from __future__ import annotations

import argparse
import os
import shutil
import sys
import zipfile
from pathlib import Path

# ── Defaults ──────────────────────────────────────────────────────────────────
# snehilsanyal/weapon-detection-test  -> publicly accessible, ~194 MB, classes: weapon
# techzizou/labeled-weapon-detection-yolo-txt -> requires ToS acceptance on Kaggle first
DEFAULT_DATASET = "snehilsanyal/weapon-detection-test"
DEFAULT_OUTPUT  = "dataset"

# Expected YOLO splits
SPLITS = ["train", "val", "test"]


def _check_kaggle_credentials() -> None:
    """Verify kaggle.json is present and formatted correctly."""
    kaggle_json = Path.home() / ".kaggle" / "kaggle.json"
    if not kaggle_json.exists():
        print("\n[FAIL] kaggle.json not found!")
        print("   Steps to fix:")
        print("   1. Go to https://www.kaggle.com/settings -> API -> Create New Token")
        print("   2. Save the downloaded kaggle.json to:")
        print(f"      {kaggle_json}")
        print("   3. Re-run this script.\n")
        sys.exit(1)
    print(f"[OK]  kaggle.json found at {kaggle_json}")


def _count_files(directory: Path, extension: str = "*") -> int:
    return len(list(directory.rglob(f"*.{extension}"))) if directory.exists() else 0


def _print_dataset_summary(output_dir: Path) -> None:
    """Print a summary of the downloaded dataset structure."""
    print("\n[INFO] Dataset Summary:")
    print(f"    {'Split':<8} {'Images':>8} {'Labels':>8}")
    print("    " + "-" * 26)
    for split in SPLITS:
        img_count   = _count_files(output_dir / "images" / split, "jpg") + \
                      _count_files(output_dir / "images" / split, "png")
        label_count = _count_files(output_dir / "labels" / split, "txt")
        print(f"    {split:<8} {img_count:>8} {label_count:>8}")
    print()


def _generate_data_yaml(output_dir: Path, class_names: list[str]) -> Path:
    """Write a standard YOLO data.yaml to the dataset directory."""
    yaml_path = output_dir / "data.yaml"
    abs_path  = str(output_dir.resolve()).replace("\\", "/")

    content = f"""# Auto-generated by download_kaggle_dataset.py
# Dataset: Weapon Detection (YOLO format)

path:  {abs_path}
train: images/train
val:   images/val
test:  images/test

nc: {len(class_names)}
names: {class_names}
"""
    yaml_path.write_text(content)
    print(f"[OK]  data.yaml written to: {yaml_path}")
    return yaml_path


def _reorganise_to_yolo_structure(base: Path) -> bool:
    """
    Normalise various dataset layouts into the canonical YOLO structure:
      base/images/train/, base/images/val/, base/labels/train/, base/labels/val/

    Supports:
      1. Already correct layout (images/train, labels/train at base)
      2. train/images + train/labels at base level
      3. weapon_detection/train/images layout (snehilsanyal dataset)
    """
    images_train = base / "images" / "train"
    labels_train = base / "labels" / "train"

    if images_train.exists() and labels_train.exists():
        print("[OK]  YOLO directory structure already in place.")
        return True

    # Layout 3: <inner_folder>/train/images  (snehilsanyal / nested datasets)
    for inner_dir in sorted(base.iterdir()):
        if not inner_dir.is_dir():
            continue
        moved_any = False
        for split in SPLITS:
            split_img = inner_dir / split / "images"
            split_lbl = inner_dir / split / "labels"
            if split_img.exists():
                dest_img = base / "images" / split
                dest_lbl = base / "labels" / split
                dest_img.mkdir(parents=True, exist_ok=True)
                dest_lbl.mkdir(parents=True, exist_ok=True)
                for f in split_img.iterdir():
                    shutil.move(str(f), dest_img / f.name)
                if split_lbl.exists():
                    for f in split_lbl.iterdir():
                        shutil.move(str(f), dest_lbl / f.name)
                print(f"   Reorganised {inner_dir.name}/{split} -> images/{split}, labels/{split}")
                moved_any = True
        if moved_any:
            try:
                shutil.rmtree(inner_dir)
            except Exception:
                pass

    if (base / "images" / "train").exists():
        return True

    # Layout 2: train/ val/ at base level, each with images/ and labels/ inside
    for split in SPLITS:
        split_img = base / split / "images"
        split_lbl = base / split / "labels"
        if split_img.exists():
            dest_img = base / "images" / split
            dest_lbl = base / "labels" / split
            dest_img.mkdir(parents=True, exist_ok=True)
            dest_lbl.mkdir(parents=True, exist_ok=True)
            for f in split_img.iterdir():
                shutil.move(str(f), dest_img / f.name)
            if split_lbl.exists():
                for f in split_lbl.iterdir():
                    shutil.move(str(f), dest_lbl / f.name)
            try:
                shutil.rmtree(base / split)
            except Exception:
                pass
            print(f"   Reorganised split '{split}' -> images/{split}, labels/{split}")

    return (base / "images" / "train").exists()



def download(dataset: str, output_dir: Path) -> Path | None:
    """
    Download and organise a Kaggle weapon detection dataset.

    Returns the path to data.yaml on success, None on failure.
    """
    _check_kaggle_credentials()

    try:
        from kaggle import KaggleApi
    except ImportError:
        print("[FAIL] kaggle package not installed. Run:  pip install kaggle")
        sys.exit(1)

    output_dir.mkdir(parents=True, exist_ok=True)
    print(f"\n[DL]  Downloading '{dataset}' -> {output_dir} ...")

    api = KaggleApi()
    api.authenticate()

    try:
        api.dataset_download_files(dataset, path=str(output_dir), unzip=False, quiet=False)
    except Exception as exc:
        print(f"[FAIL] Download failed: {exc}")
        print("   Check dataset name with: kaggle datasets list -s weapon")
        print("   If 403 Forbidden, you need to accept the dataset ToS on kaggle.com first.")
        sys.exit(1)

    # ── Unzip all archives ────────────────────────────────────────────────────
    zips = list(output_dir.glob("*.zip"))
    if not zips:
        print("[WARN] No zip file found - dataset may already be extracted.")
    else:
        for z in zips:
            print(f"[ZIP] Extracting {z.name} ...")
            with zipfile.ZipFile(z) as zf:
                zf.extractall(output_dir)
            z.unlink()

    print("[OK]  Download and extraction complete.\n")

    # ── Reorganise into YOLO structure ────────────────────────────────────────
    valid = _reorganise_to_yolo_structure(output_dir)
    if not valid:
        print("[WARN] Could not auto-detect YOLO structure. Please check the dataset layout manually.")
        print(f"       Expected: {output_dir}/images/train/ and {output_dir}/labels/train/")

    # ── Detect class names from existing yaml ─────────────────────────────────
    existing_yaml = output_dir / "data.yaml"
    class_names   = ["weapon"]   # Default for snehilsanyal dataset (single class)

    # Try to read class names from any existing yaml in the dataset
    for yaml_candidate in output_dir.rglob("*.yaml"):
        content = yaml_candidate.read_text(errors="ignore")
        if "names:" in content:
            print(f"[INFO] Found existing yaml: {yaml_candidate} - regenerating with absolute path.")
            break

    yaml_path = _generate_data_yaml(output_dir, class_names)

    # ── Summary ───────────────────────────────────────────────────────────────
    _print_dataset_summary(output_dir)

    print("[NEXT] Steps:")
    print("    1. Verify the dataset structure above looks correct.")
    print(f"    2. Open {yaml_path} and confirm class names match your labels.")
    print("    3. Update backend/.env:  WEAPON_CLASS_IDS=0")
    print("    4. Run training:")
    print("       python scripts/train_custom_model.py\n")

    return yaml_path


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Download Kaggle weapon detection dataset",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        "--dataset",
        default=DEFAULT_DATASET,
        help=f'Kaggle dataset ID (default: {DEFAULT_DATASET})',
    )
    parser.add_argument(
        "--output",
        default=DEFAULT_OUTPUT,
        help=f"Output directory (default: {DEFAULT_OUTPUT})",
    )
    args = parser.parse_args()
    download(args.dataset, Path(args.output))
